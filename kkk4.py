def main():
    try:
        # На вход подаются два целых числа, каждое на отдельной строке
        n = int(input())  # Количество школьников
        k = int(input())  # Количество мандаринов

        # Проверка на корректность данных (деление на 0 школьников невозможно)
        if n <= 0:
            print("Ошибка: количество школьников должно быть больше нуля.")
            return

        # Расчеты
        per_student = k // n  # Сколько мандаринов достанется каждому школьнику
        in_basket = k % n  # Сколько мандаринов останется в корзине

        # Программа должна вывести два числа, каждое на отдельной строке
        print(per_student)
        print(in_basket)

    except ValueError:
        print("Ошибка: входные данные должны быть целыми числами.")


if __name__ == "__main__":
    main()
